"""A tiny reporter seam the loop calls at each step.

The default :class:`NoopReporter` does nothing (keeps the loop testable and
silent). The CLI passes a console reporter for step display; Phase 9's event bus
can publish through the same hooks. Reporters receive only short, curated
strings — never raw secrets (transcripts already redact separately).
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable


@runtime_checkable
class Reporter(Protocol):
    def assistant_text(self, text: str) -> None: ...
    def tool_started(self, name: str, summary: str) -> None: ...
    # Rich preview of an about-to-run action: a boxed shell command with its
    # risk-coloured reasoning, or an "updates" diff for a file edit. ``request``
    # is a permissions.PermissionRequest (kept loosely typed to avoid a cycle).
    def action(self, request: object) -> None: ...
    def tool_finished(self, name: str, ok: bool, detail: str) -> None: ...
    def permission(self, tool: str, outcome: str, reason: str | None) -> None: ...
    def info(self, text: str) -> None: ...


class NoopReporter:
    def assistant_text(self, text: str) -> None: ...
    def tool_started(self, name: str, summary: str) -> None: ...
    def action(self, request: object) -> None: ...
    def tool_finished(self, name: str, ok: bool, detail: str) -> None: ...
    def permission(self, tool: str, outcome: str, reason: str | None) -> None: ...
    def info(self, text: str) -> None: ...
